"use strict";

console.log("WHILE");
let whileI = 25;
while (whileI >= 0) {
  console.log(whileI);
  whileI--;
}

console.log("DO WHILE");
let doWhileI = 25;
do {
  console.log(doWhileI);
  doWhileI--;
} while (doWhileI >= 0);

console.log("FOR");
for (let i = 25; i >= 0; i--) {
  console.log(i);
}
